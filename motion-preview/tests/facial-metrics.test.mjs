import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
const src=readFileSync(new URL('../facial-metrics.js',import.meta.url),'utf8');
const {facialMetrics,buildTimeline}=await import('data:text/javascript;base64,'+Buffer.from(src).toString('base64'));
assert.equal(facialMetrics([]),null);
const points=Array.from({length:478},()=>({x:.5,y:.5,z:0}));
points[33]={x:.2,y:.4};points[263]={x:.8,y:.4};
points[133]={x:.35,y:.4};points[362]={x:.65,y:.4};
points[159]={x:.3,y:.38};points[145]={x:.3,y:.43};
points[386]={x:.7,y:.38};points[374]={x:.7,y:.43};
points[13]={x:.5,y:.56};points[14]={x:.5,y:.60};points[1]={x:.5,y:.5};
const metric=facialMetrics(points);
assert.ok(metric.mouth_open>0);
assert.ok(metric.left_eye_open>0);
const t=buildTimeline([{time:0,landmarks:points},{time:.2,landmarks:points},{time:.4,landmarks:[]}]);
assert.equal(t.valid_frames,2);
assert.equal(t.metrics.length,3);
assert.equal(t.summary.mouth_open.jump_count,0);
console.log('Facial metrics tests passed');
